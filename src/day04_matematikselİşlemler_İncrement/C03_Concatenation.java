package day04_matematikselİşlemler_İncrement;

public class C03_Concatenation {
    public static void main(String[] args) {


        /*Eger string ile + kullanılırsa
         bu toplama degeri birlestirme (concatenation)
         olarak adlandırılır
        */
        System.out.println("Ali" + " " + "okula" + " " + "gitti");
        // Aki okula gitti.

        System.out.println("sayi degeri : " + 2 + 3); // "sayi degeri : 2" + 3
                                                      // "Sayi degeri 23"
        System.out.println("sayi degeri : " + (2 + 3)); // sayi degeri : 5



        //System.out.println("a" - 2);
        //System.out.println("a" / 2);
        //System.out.println("a" *2);

        // string matematiksel islemlere acık degildir.
        // sadece + islemini birlestirme(concatenation) olarak yazar.





    }
}
